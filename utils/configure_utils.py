  # generated asset build statements
  for dep, info in targets.items():
    if info != {}:
      # emulate the original makefile rule of
      # having `tools/gfx` run conditionally
      rule = info['rule']
      if rule in ['2BPP', '1BPP']:
        if info['flags'].get('tools_gfx', None):
          rule += '_GFX'
      (build_dir / dep / '..').resolve().mkdir(parents=True, exist_ok=True)
      # any non-absolute input is treated as part of the build dir
      tr_inputs = []
      for i in info['inputs']:
        ii = str(i)
        if ii[0] != '/':
          tr_inputs.append(str(build_dir / i))
        else:
          tr_inputs.append(ii)
