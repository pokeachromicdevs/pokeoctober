def find_sys_tool(name: str) -> str:
  found = shutil.which(name)
  if found and len(found) > 0:
    return found
  return None

def find_tool(tools_dir: Path, name: str) -> str:
  candidate = tools_dir / name
  if candidate.exists():
    return candidate
  # Fall back to PATH
  return find_sys_tool(name)

def scan_file(scan_includes: str, path: Path) -> list[str]:
  result = subprocess.run(
    [scan_includes, str(path)],
    capture_output=True, text=True, check=True,)
  deps = result.stdout.strip().split()
  return [d for d in deps if d]

NINJA_HEADER = '''\
# generated by utils/configure.py, do not edit
ninja_required_version = 1.5

'''

def Rule(out: list[str], name: str, command: str, description: str = '', generator: bool = False) -> str:
  lines = [f'rule {name}', f'  command = {command}']
  if description:
    lines.append(f'  description = {description}')
  if generator:
      lines.append(f'  generator = 1')
  out.append('\n'.join(lines) + '\n')

def Target(out: list[str], output: list[str], rule: str, inputs: list[str],
        implicit: list[str] = None, implicit_out: list[str] = None,
        order_only: list[str] = None, variables: dict = None) -> str:
  outs = ' '.join(shlex.quote(str(i)) for i in output)
  if implicit_out:
    outs += ' | ' + ' '.join(shlex.quote(i) for i in implicit_out)
  ins = ' '.join(shlex.quote(str(i)) for i in inputs)
  line = f'build {outs}: {rule} {ins}'
  if implicit:
    line += ' | ' + ' '.join(shlex.quote(i) for i in implicit)
  elif order_only:
    line += ' || ' + ' '.join(shlex.quote(i) for i in order_only)
  lines = [line]
  if variables:
    for k, v in variables.items():
      lines.append(f'  {k} = {v}')
  out.append('\n'.join(lines) + '\n')

